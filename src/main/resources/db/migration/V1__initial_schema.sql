CREATE TABLE app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK(role IN ('CITIZEN','SUPPORTER')),
 phone_cipher VARCHAR(512),
 auto_share_high BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE risk_rule (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category VARCHAR(60) NOT NULL,
 expression VARCHAR(500) NOT NULL,
 explanation VARCHAR(500) NOT NULL,
 weight INTEGER NOT NULL CHECK(weight BETWEEN 0 AND 100)
);
CREATE TABLE threat_analysis (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 kind VARCHAR(20) NOT NULL,
 content_cipher TEXT NOT NULL,
 score INTEGER NOT NULL CHECK(score BETWEEN 0 AND 100),
 level VARCHAR(20) NOT NULL,
 reasons_json TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_analysis_user_date ON threat_analysis(user_id,created_at);
CREATE TABLE elo_link (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 supporter_id BIGINT REFERENCES app_user(id) ON DELETE CASCADE,
 support_email VARCHAR(254) NOT NULL,
 relationship_label VARCHAR(60) NOT NULL,
 state VARCHAR(30) NOT NULL,
 token_hash VARCHAR(64),
 expires_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(owner_id,support_email)
);
CREATE TABLE support_alert (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 link_id BIGINT NOT NULL REFERENCES elo_link(id) ON DELETE CASCADE,
 analysis_id BIGINT NOT NULL REFERENCES threat_analysis(id) ON DELETE CASCADE,
 state VARCHAR(20) NOT NULL,
 email_state VARCHAR(30) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 acknowledged_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(link_id,analysis_id)
);
CREATE INDEX idx_alert_link_state ON support_alert(link_id,state);
CREATE TABLE password_reset (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 token_hash VARCHAR(64) NOT NULL UNIQUE,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 used BOOLEAN NOT NULL DEFAULT FALSE
);
